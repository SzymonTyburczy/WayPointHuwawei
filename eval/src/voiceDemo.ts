// A scripted voice conversation with the simulated demo app, in conditions A
// (defective) and C (hand-fixed), using the real C++ core and the same
// VoiceController the app uses. Writes results/voice-demo.md.
//
//   npm run voice-demo                      lexical baseline as the guide's "model"
//   npm run voice-demo -- --backend remote  llama-server on :8080
import { mkdirSync, writeFileSync } from 'fs';
import { join, resolve } from 'path';

import { GuideSession, type Clock, type GuideState } from '../../packages/waypoint-sdk/src/guide/GuideSession';
import type { LlmBackend } from '../../packages/waypoint-sdk/src/llm/LlmBackend';
import { RemoteBackend } from '../../packages/waypoint-sdk/src/llm/RemoteBackend';
import { createCliCore } from '../../packages/waypoint-sdk/src/node/cliCore';
import { VoiceController } from '../../packages/waypoint-sdk/src/voice/VoiceController';
import type { Condition } from '../../examples/demo-app/src/app/spec';
import { LexicalBackend } from './baseline';
import { Simulator } from './simulator';

import tasksFile from '../tasks.json';

class InstantClock implements Clock {
  t = 0;
  now = () => this.t;
  sleep = async (ms: number) => {
    this.t += ms;
  };
}

const SCRIPT: Record<Condition, string[]> = {
  A: ['co tu jest?', 'sprawdź dostępność', 'what is here?', 'see my past tickets'],
  B: [],
  C: ['co tu jest?', 'gdzie jestem', 'see my past tickets', 'where am I', 'powtórz', 'sprawdź dostępność'],
};

async function converse(condition: Condition, backend: LlmBackend): Promise<string[]> {
  const core = createCliCore();
  const sim = new Simulator(core, condition);
  const lines: string[] = [];
  let state: GuideState = { status: 'idle', goal: '', step: 0, caption: '', reminder: false, history: [] };
  let voice: VoiceController;
  const session = new GuideSession({
    core,
    backend,
    snapshot: () => sim.snapshot(),
    clock: new InstantClock(),
    canGoBack: () => sim.canGoBack(),
    options: { pollMs: 5_000 },
    onState: (s) => {
      state = s;
      voice.onGuideState(s);
    },
    onStep: (e) => {
      sim.apply(e.action, e.snapshot);
      lines.push(`  *(user taps; now on ${sim.screen})*`);
      // The lexical baseline never answers "done"; stop at the task's target like the
      // evaluation does, and say so.
      const goal = state.goal.toLowerCase();
      const target = tasksFile.tasks.find((t) => t.phrasings.some((p) => p.toLowerCase() === goal))?.target;
      if (target && sim.isVisible(target)) {
        lines.push('  *(target reached: the evaluation predicate stops the guide here; a model would answer "done")*');
        session.stop();
      }
    },
  });
  let running: Promise<GuideState> = Promise.resolve(state);
  voice = new VoiceController({
    core,
    lang: 'auto',
    takeSnapshot: async () => sim.snapshot(),
    startGuide: (goal) => (running = session.start(goal)),
    stopGuide: () => session.stop(),
    getGuide: () => state,
    audit: async () => core.audit(sim.snapshot()),
    speak: (text) => {
      lines.push(`- **Waypoint:** ${text}`);
    },
    viewport: () => ({ x: 0, y: 0, w: 360, h: 780 }),
  });
  for (const utterance of SCRIPT[condition]) {
    lines.push(`- **User:** “${utterance}”`);
    await voice.handle(utterance);
    await running;
  }
  return lines;
}

async function main() {
  const args = process.argv.slice(2);
  const remote = args.includes('--backend') && args[args.indexOf('--backend') + 1] === 'remote';
  const backend: LlmBackend = remote ? new RemoteBackend({ url: 'http://127.0.0.1:8080', isDev: true, timeoutMs: 60_000 }) : new LexicalBackend();
  const info = await backend.info();
  const out = [
    '# Voice control demo (simulated)',
    '',
    `Guide backend: ${info.kind} (${info.model}). Generated by \`npm run voice-demo\`; replies are what the app speaks.`,
    '',
    '## Condition A — defective app',
    '',
    ...(await converse('A', backend)),
    '',
    '## Condition C — labels fixed',
    '',
    ...(await converse('C', backend)),
    '',
  ].join('\n');
  const dir = resolve(__dirname, '..', 'results');
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, 'voice-demo.md'), out);
  console.log(out);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
